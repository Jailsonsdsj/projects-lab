// pnpm design:extract — pulls the design tokens and the component reference CSS
// out of the Claude Design bundle (docs/design/*.html) into readable files:
//   docs/design/tokens.css      the source D-01 copies into packages/web
//   docs/design/components.css  the reference D-02 and D-03 build components from
// and generates the app's stylesheet from the second:
//   packages/web/src/styles/components.css  minus the canvas-only state selectors
// Every page of the bundle embeds its own copy of both; they must all agree.
// Re-run after committing a new bundle.
//
// Bundle format: each export holds a `__bundler/manifest` of gzip+base64 pages;
// each page holds a `__bundler/template` JSON string whose <style> blocks are
// the CSS.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { gunzipSync } from "node:zlib";

const DESIGN_DIR = path.join(import.meta.dirname, "../docs/design");
const APP_COMPONENTS_CSS = path.join(
  import.meta.dirname,
  "../packages/web/src/styles/components.css",
);

/** Forced states the canvas uses to draw a state without a pointer. The bundle
 *  says they go in the app; the real :hover / :active / :focus-visible stay. */
const CANVAS_ONLY = /\.is-(hover|pressed|focus)(?![\w-])/;

const OUTPUTS = {
  "tokens.css": "Projects Lab — design tokens",
  "components.css": "Projects Lab — component reference CSS",
} as const;

type ManifestEntry = { mime: string; compressed?: boolean; data: string };

function scriptBlock(html: string, type: string): string {
  const match = html.match(
    new RegExp(`<script type="__bundler/${type}">([\\s\\S]*?)</script>`),
  );
  if (!match?.[1]) throw new Error(`no __bundler/${type} block`);
  return match[1];
}

function pages(bundleFile: string): string[] {
  const html = readFileSync(path.join(DESIGN_DIR, bundleFile), "utf8");
  const manifest: Record<string, ManifestEntry> = JSON.parse(
    scriptBlock(html, "manifest"),
  );
  return Object.values(manifest)
    .filter((entry) => entry.mime === "text/html")
    .map((entry) => {
      const bytes = Buffer.from(entry.data, "base64");
      return (entry.compressed ? gunzipSync(bytes) : bytes).toString("utf8");
    });
}

function styleBlocks(page: string): string[] {
  const template: string = JSON.parse(scriptBlock(page, "template"));
  return [...template.matchAll(/<style>([\s\S]*?)<\/style>/g)].map(
    (m) => m[1] ?? "",
  );
}

const bundles = readdirSync(DESIGN_DIR).filter((f) => f.endsWith(".html"));
if (bundles.length === 0) throw new Error(`no bundle .html in ${DESIGN_DIR}`);

const copies = new Map<string, Set<string>>(
  Object.keys(OUTPUTS).map((name) => [name, new Set()]),
);
let pageCount = 0;
for (const bundle of bundles) {
  for (const page of pages(bundle)) {
    pageCount++;
    for (const css of styleBlocks(page)) {
      for (const [name, title] of Object.entries(OUTPUTS)) {
        if (css.slice(0, 400).includes(title)) copies.get(name)?.add(css);
      }
    }
  }
}

for (const [name, versions] of copies) {
  if (versions.size !== 1) {
    throw new Error(
      `${name}: expected one version across ${pageCount} pages, found ${versions.size}`,
    );
  }
  const [css = ""] = versions;
  const header = `/* Generated by scripts/design-extract.ts from docs/design/*.html.
   Reference only: do not edit, and nothing imports it. Re-run after a bundle update. */\n\n`;
  writeFileSync(path.join(DESIGN_DIR, name), header + css.trimStart());
  console.log(`docs/design/${name}: one version across ${pageCount} pages`);
  if (name === "components.css") writeAppComponents(css);
}

/** Splits a selector list on top-level commas (not those inside :is(), :not()…). */
function splitSelectors(list: string): string[] {
  const parts: string[] = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < list.length; i++) {
    const ch = list[i];
    if (ch === "(") depth++;
    else if (ch === ")") depth--;
    else if (ch === "," && depth === 0) {
      parts.push(list.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(list.slice(start));
  return parts.map((p) => p.trim()).filter(Boolean);
}

/** The bundle's component CSS (flat rules, no at-rules) minus every selector
 *  that only exists for the canvas; a rule left with no selector is dropped. */
function writeAppComponents(css: string) {
  if (/@[a-z]/i.test(css.replace(/\/\*[\s\S]*?\*\//g, ""))) {
    throw new Error(
      "components.css gained an at-rule; extend writeAppComponents",
    );
  }
  let dropped = 0;
  const out = css.replace(
    /(^|[}\n])([^{}]*?)\{([^{}]*)\}/g,
    (whole, lead: string, prelude: string, body: string) => {
      const comment = prelude.match(/^[\s\S]*\*\//)?.[0] ?? "";
      const selectorText = prelude.slice(comment.length);
      const indent = selectorText.match(/^\s*/)?.[0] ?? "";
      const selectors = splitSelectors(selectorText);
      const kept = selectors.filter((sel) => !CANVAS_ONLY.test(sel));
      dropped += selectors.length - kept.length;
      if (kept.length === selectors.length) return whole;
      if (kept.length === 0) return `${lead}${comment}`;
      return `${lead}${comment}${indent}${kept.join(", ")} {${body}}`;
    },
  );
  const header = `/* Generated by scripts/design-extract.ts from the Claude Design bundle: the
   bundle's component CSS minus its canvas-only .is-hover / .is-pressed / .is-focus
   selectors. Do not edit; app-only rules go in their own file. */\n\n`;
  writeFileSync(APP_COMPONENTS_CSS, header + out.trimStart());
  console.log(
    `packages/web/src/styles/components.css: ${dropped} canvas-only selectors removed`,
  );
}
